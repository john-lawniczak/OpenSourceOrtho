"""Build unreviewed crown-based inspection frames; never estimate a bite or scale.

Uses the frozen private week-18 draft and selected trimmed H4 bundle. Only rigid
view axes, anchors and provenance hashes are emitted, never annotation arrays.
"""
import base64
import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CASE = ROOT / "datasets/spec-07b7031938c84b1a9c98517b8bc4cdd3"


def crown_frame(raw, annotation, arch):
    digest = hashlib.sha256(raw).hexdigest()
    count = int.from_bytes(raw[80:84], "little")
    if len(raw) != 84 + count * 50 or annotation["source_sha256"] != digest:
        raise ValueError("Scan/annotation binding mismatch")
    dtype = np.dtype([("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attribute", "<u2")])
    triangles = np.frombuffer(raw, dtype=dtype, offset=84)["vertices"].astype(float)
    labels = np.frombuffer(base64.b64decode(annotation["labels_base64"], validate=True), dtype=np.uint8)
    if len(labels) != count or not np.isfinite(triangles).all():
        raise ValueError("Invalid source geometry or face labels")
    centers = {int(t): np.median(triangles[labels == t].mean(axis=1), axis=0)
               for t in np.unique(labels) if t}
    incisors = [11, 21] if arch == "upper" else [31, 41]
    molars = [16, 17, 26, 27] if arch == "upper" else [36, 37, 46, 47]
    if not all(t in centers for t in incisors + molars) or len(centers) < 10:
        raise ValueError("Insufficient crown regions for this inspection frame")
    points = np.array(list(centers.values()))
    eigenvalues, axes = np.linalg.eigh(np.cov(points.T))
    if eigenvalues[1] < 1e-8:
        raise ValueError("Crown centers do not define an inspection plane")
    up = axes[:, 0]
    # Known crown-facing scanner hemisphere; PCA itself has an arbitrary sign.
    toward_crowns = np.array([0, 0, -1] if arch == "upper" else [0, -1, 0])
    if up @ toward_crowns < 0:
        up = -up
    anterior = np.mean([centers[t] for t in incisors], axis=0)
    posterior = np.mean([centers[t] for t in molars], axis=0)
    front = anterior - posterior
    front -= up * (front @ up)
    if np.linalg.norm(front) < 1e-8:
        raise ValueError("Crown regions do not define an anterior direction")
    front /= np.linalg.norm(front)
    right = np.cross(up, front)
    crown_points = triangles[labels != 0].reshape(-1, 3)
    crown_edge = float(np.quantile(crown_points @ up, .99))
    origin = anterior + up * (crown_edge - anterior @ up)
    return {"source_sha256": digest, "arch": arch, "up": up.tolist(), "front": front.tolist(),
            "origin": origin.tolist(), "reviewed": False, "units": "unverified",
            "annotation_sha256": hashlib.sha256(json.dumps(annotation, sort_keys=True).encode()).hexdigest(),
            "crown_width_scan_units": float(np.ptp(points @ right)),
            "crown_depth_scan_units": float(np.ptp(points @ front))}


def main():
    upper = CASE / "visits/progress-02/captures/upper-clean/progress-02-upper-clean.stl"
    annotation = json.loads((CASE / "private/painting-seeds/week-18/upper-corrections.json").read_text())
    bundle = json.loads((CASE / "private/surface-edits/week-18-lower-cleaned/repair-bundle.json").read_text())
    frames = [crown_frame(upper.read_bytes(), annotation, "upper"),
              crown_frame(base64.b64decode(bundle["stlBase64"], validate=True), bundle["labels"], "lower")]
    # The original H4 shares coordinates with its exact-subset trim. Retain the
    # same view frame when the private trim is unavailable, without copying labels.
    frames.append({**frames[1], "source_sha256": bundle["scan"]["repair"]["sourceSha256"],
                   "frame_from_trim_sha256": frames[1]["source_sha256"]})
    target = ROOT / "ui/scan_history_frames.js"
    target.write_text("// Generated by tools/build_week_eighteen_display_frames.py.\n"
                      "// Unreviewed inspection frames from draft crowns; not bite or motion registration.\n"
                      "export const historyFrames = " + json.dumps(frames, indent=2) + ";\n")
    for frame in frames[:2]:
        print(frame["arch"], "crown-center width:", round(frame["crown_width_scan_units"], 3), "scan units")


if __name__ == "__main__":
    main()
